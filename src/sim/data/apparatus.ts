export const APPARATUS_BY_ID: Record<string, ApparatusSpec> = Object.fromEntries(APPARATUS.map((a) => [a.id, a]));

export function getSpec(specId: string): ApparatusSpec {
  const spec = APPARATUS_BY_ID[specId];
  if (!spec) throw new Error(`Unknown apparatus spec: ${specId}`);
  return spec;
}

